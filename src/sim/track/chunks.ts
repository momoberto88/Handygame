import type { WorldId } from '../types';

/**
 * Hand-built track pieces. Each map is bottom-aligned: the last line is row 13, the line above is
 * row 12 (the regular ground line), and so on upwards. Missing rows at the top are empty.
 * Every chunk must enter and leave with solid ground at row 12 so pieces can be chained.
 *
 *   .  empty            #  solid           /  ramp up         \  ramp down
 *   =  one-way ledge    ^  spikes          ?  item box        o  coin
 *   S  saw              M  swinging saw    C  crusher (hangs from this solid cell)
 *   J  jump pad         B  boost pad
 */
export interface ChunkDef {
  name: string;
  /** 1 = easy … 3 = hard. */
  difficulty: 1 | 2 | 3;
  /** Worlds this chunk may appear in; omitted = every world. */
  worlds?: WorldId[];
  map: string;
}

